"""The compiled rule's direction, versioned: v1 as committed, v2 read in the rule's own cell.

**This file is the registration.** Everything below is stated before any count was taken, and the
first commit of this module carries nothing but these constants: no sign is read, no element is
opened, no file is written. The implementation arrives in a later commit and may not restate,
widen or soften a single sentence here.

**The defect.** A compiled rule's direction is the sign of the single most extreme of 371
AlphaGenome tracks: `predict.enhancer_target.predict_target` takes the larger of the biggest drop
and the biggest rise over every track, and `attribution/compile.py` writes `activates` or
`inhibits` from it (`compile.element_axes`, `compile.compile_chromosome`). One track out of 371,
selected for being extreme, decides what the program asserts about molecular action, and the
assertion reads the same whether the effect was large or a hair above `MIN_EFFECT`.

**What v2 changes, and what it does not.** v2 changes what a rule *asserts* about direction. It
proves nothing. No measurement in this lane says a v2 call is right, no agreement rate against any
benchmark is computed here, and nothing here is validation (`NOT_VALIDATION`). v2 is not a gain in
accuracy (`NOT_AN_IMPROVEMENT`); it declines to state a direction the evidence in one cell does not
carry, which is a different claim and a weaker one.

**v1 stays the default and stays byte-identical.** `DIRECTION_RULE_DEFAULT` is `V1`, v1 reproduces
the committed expression exactly, and no compiled program is regenerated by this lane.
"""

