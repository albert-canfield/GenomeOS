# ---- the tokens, and the value that is neither of them --------------------------------------------

#: The two action tokens the compiler writes on a `rule` line. The byte-identity test holds v1's
#: output to the committed program, so these cannot drift from what compile.py used to write.
ACTIVATES = "activates"
INHIBITS = "inhibits"

MOLECULAR_ACTION_UNKNOWN = (
    "molecular action unknown: the sign rule did not resolve in the rule's own assigned cell"
)

V2_NOT_WRITABLE = (
    "the BioLang `rule` head takes one action token and the grammar has none for a direction that "
    "did not resolve, so an unresolved v2 call cannot be written into a program. Writing `inhibits` "
    "or `activates` for it would be the defect v2 exists to stop, so the compiler refuses instead. "
    "Adding a token is a change to the grammar and to every compiled program, which this lane does "
    "not make"
)


class UnresolvedDirectionError(Exception):
    """Raised when a direction is read off a call that did not resolve. Never caught in this module."""


class _Unresolved:
    """The unresolved direction, as a value of its own kind.

    It equals nothing but itself, so `call.token == ACTIVATES` and `call.token == INHIBITS` are both
    false and `call.token in (ACTIVATES, INHIBITS)` is false. `bool()` raises rather than answering,
    so `if token:` cannot quietly read it as a direction. There is one instance.
    """

    __slots__ = ()
    _instance: _Unresolved | None = None

    def __new__(cls) -> _Unresolved:
        if cls._instance is None:
            cls._instance = super().__new__(cls)
        return cls._instance

    def __repr__(self) -> str:
        return "UNRESOLVED"

    def __str__(self) -> str:
        return "UNRESOLVED"

    def __eq__(self, other: object) -> bool:
        return other is self

    def __ne__(self, other: object) -> bool:
        return other is not self

    def __hash__(self) -> int:
        return hash("genomeos.attribution.direction_v2.UNRESOLVED")

    def __bool__(self) -> bool:
        raise UnresolvedDirectionError(UNRESOLVED_IS_FIRST_CLASS)


#: The unresolved direction. `UNRESOLVED_MEANS` says what it means and what it does not.
UNRESOLVED = _Unresolved()


@dataclass(frozen=True)
class DirectionCall:
    """One rule's direction under one version of the rule, with the evidence it was read from."""

    version: int
    token: str | _Unresolved
    cell: str
    values: tuple[tuple[str, float], ...] = ()
    reason: str | None = None

    @property
    def resolved(self) -> bool:
        return self.token is not UNRESOLVED

    @property
    def action(self) -> str:
        """The token the compiler would write, or `UnresolvedDirectionError`. There is no third return."""
        if self.token is UNRESOLVED:
            raise UnresolvedDirectionError(f"{self.reason}: {V2_NOT_WRITABLE}")
        assert isinstance(self.token, str)
        return self.token

    @property
    def molecular_action(self) -> str:
        """What the call says about molecular action: a token, or that it is unknown."""
        return MOLECULAR_ACTION_UNKNOWN if self.token is UNRESOLVED else self.action

    def to_dict(self) -> dict[str, Any]:
        return {
            "direction_rule_version": self.version,
            "molecular_action": self.molecular_action,
            "resolved": self.resolved,
            "assigned_cell": self.cell,
            "values_in_assigned_cell": [[s, v] for s, v in self.values],
            "unresolved_reason": self.reason,
        }


# ---- v1: the committed rule, unchanged -------------------------------------------------------------


def _v1(pc: dict[str, Any]) -> DirectionCall:
    """`activates` when predicted_coding['action'] == 'activates', `inhibits` otherwise. As committed."""
    token = ACTIVATES if pc.get("action") == "activates" else INHIBITS
    return DirectionCall(version=V1, token=token, cell=pc.get("tissue") or "")


# ---- v2: the sign in the rule's own assigned cell ---------------------------------------------------


def retained_values(row: dict[str, Any], cell: str) -> tuple[tuple[str, float], ...]:
    """Every value the cached gene row retains for one cell name, with the field it came from.

    `CELL_EVIDENCE` names the three and says there are no others on a legacy row. A value whose
    tissue field is empty belongs to no cell and is never matched, so the zero a gene row carries
    for a direction no track took is not read as a value of any cell.
    """
    out: list[tuple[str, float]] = []
    if cell and row.get("max_drop_tissue") == cell:
        out.append(("max_drop", float(row["max_drop_log2fc"])))
    if cell and row.get("max_rise_tissue") == cell:
        out.append(("max_rise", float(row["max_rise_log2fc"])))
    by_cell = row.get("by_cell") or {}
    if cell and by_cell.get(cell) is not None:
        out.append(("by_cell", float(by_cell[cell])))
    return tuple(out)


def _signs_disagree(values: list[float]) -> bool:
    """`predict.enhancer_target`'s own reading of disagreement, imported and not restated."""
    return bool(et._cell_summary(values)["signs_disagree"])


def _v2(pc: dict[str, Any], row: dict[str, Any] | None) -> DirectionCall:
    """`SIGN_RULE_V2`, word for word: two values, one sign, over the floor, or UNRESOLVED."""
    cell = pc.get("tissue") or ""
    if not cell.strip():
        return DirectionCall(V2, UNRESOLVED, "", (), "context_unknown")
    if row is None:
        return DirectionCall(V2, UNRESOLVED, cell, (), "no_row_for_target")
    found = retained_values(row, cell)
    values = [v for _, v in found]
    if not values:
        return DirectionCall(V2, UNRESOLVED, cell, found, "no_value_for_cell")
    if len(values) < 2:
        return DirectionCall(V2, UNRESOLVED, cell, found, "one_value_only")
    if len(set(values)) < 2:  # AMENDMENT_1: two fields, one track
        return DirectionCall(V2, UNRESOLVED, cell, found, "one_track_seen_twice")
    if any(v == 0.0 for v in values):
        return DirectionCall(V2, UNRESOLVED, cell, found, "zero_value_in_cell")
    if _signs_disagree(values):
        return DirectionCall(V2, UNRESOLVED, cell, found, "signs_disagree_in_cell")
    if max(abs(v) for v in values) < MAGNITUDE_FLOOR:
        return DirectionCall(V2, UNRESOLVED, cell, found, "below_magnitude_floor")
    token = INHIBITS if values[0] > 0 else ACTIVATES
    return DirectionCall(V2, token, cell, found)


# ---- the dispatch, and the seam the compiler calls ---------------------------------------------------


def direction_call(
    pc: dict[str, Any],
    version: int = DIRECTION_RULE_DEFAULT,
    *,
    chrom: str | None = None,
    element_id: str | None = None,
    row: dict[str, Any] | None = None,
) -> DirectionCall:
    """The direction of one predicted rule under `version`.

    v1 reads nothing but `pc` and opens no file, so the default path costs what it always cost. v2
    needs the target gene's cached row: it is taken from `row` when given, else from the deletion
    cache for `chrom`/`element_id`, which is read from disk and never from the model.
    """
    if version == V1:
        return _v1(pc)
    if version != V2:
        raise ValueError(f"no direction rule version {version!r}; the versions are {V1} and {V2}")
    if row is None and chrom and element_id:
        row = cached_row(chrom, element_id, pc.get("gene"))
    return _v2(pc, row)


def compiled_action(
    pc: dict[str, Any],
    version: int = DIRECTION_RULE_DEFAULT,
    *,
    chrom: str | None = None,
    element_id: str | None = None,
) -> str:
    """The action token the compiler writes, or `UnresolvedDirectionError` when the rule did not resolve.

    This is the one seam: `compile.element_axes` and `compile.compile_chromosome` read their
    direction here and nowhere else. Under `V1` it returns exactly what the two committed
    expressions returned, which `tests/test_direction_v2.py` holds to the compiled program byte for
    byte. Under `V2` an unresolved call raises `V2_NOT_WRITABLE` rather than naming a direction.
    """
    return direction_call(pc, version, chrom=chrom, element_id=element_id).action


# ---- the cached rows, read from disk ---------------------------------------------------------------


def cached_row(chrom: str, element_id: str, gene: str | None) -> dict[str, Any] | None:
    """The cached gene row for one element's named target, or None.

    `predict.enhancer_target.load_cached` is the project's own reader and is used unchanged: the
    per-element file when there is one, else the chromosome's packed archive, which it reads once per
    process. Disk only - 0 model requests, no network, no money.
    """
    answer = et.load_cached(chrom, element_id)
    if not answer or not gene:
        return None
    for row in answer.get("genes", []):
        if row.get("gene") == gene:
            return row
    return None
