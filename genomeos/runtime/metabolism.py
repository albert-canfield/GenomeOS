"""Stage 3's arithmetic: the ATP a cell can make per hour, from what, and who is cut when it cannot.

Stage 2 made a cost mean something by holding it against a pool; stage 4 found that a pool's `size`
is a standing stock while a division's cost is a draw over a cycle, and that nothing converted between
them (§9.4). This module is the conversion. A pool whose `regenerates` names the processes of core
metabolism — `from Glycolysis, TCA, OXPHOS` — is refilled per hour by a reduced module (§6): glucose
through glycolysis to pyruvate, pyruvate oxidised through the TCA cycle, the electron pairs through
oxidative phosphorylation to oxygen, and whatever pyruvate is not oxidised reduced to lactate.

**The engine holds no stoichiometric number.** Every yield, every P/O ratio and the oxygen per electron
pair are `param`s the program states, normally by importing `bio.std.core_metabolism`; a program that
does not is refused, and one that overrides a number does so with its own evidence. The cell's own
facts are the program's too: the glucose uptake ceiling is the `Glucose` pool's `regenerates` rate,
the oxygen supply the `O2` pool's, the mitochondrial capacity `param oxphos_capacity_per_copy` (electron
pairs per hour per copy) times the copies of every compartment whose genome reads chrM, and the
fraction of glycolytic flux through the 2,3-BPG shunt `param bpg_shunt` (none when it is not stated,
as a protein with no half-life is not degraded).

**The one structural claim, stated rather than hidden.** Supply follows demand, and pyruvate is
oxidised as far as oxygen, capacity and glucose allow before any becomes lactate. That is a
Pasteur-competent cell by construction, so lowering oxygen raising glucose uptake is a property of
this routing, not a finding about cells; and a cell that ferments with oxygen present (the Warburg
effect) cannot be written in stage 3.

**Yields with their spread.** Every number that depends on a yield is computed twice: the `high` arm
(P/O `po_nadh` and `po_fadh2`, cytosolic NADH entering through the malate-aspartate shuttle as NADH)
and the `low` arm (`po_nadh_low` and `po_fadh2_low`, cytosolic NADH entering through the glycerol
3-phosphate shuttle as FADH2). Nothing picks one.

**Heteroplasmy** removes the OXPHOS capacity of the copies that carry a declared variant
(`Compartment.heteroplasmy`). The engine holds no table of which mtDNA variants are pathogenic. Because
the cut is to capacity, not to flux, a cell with a reserve keeps its OXPHOS flux unchanged until the
copies left cannot carry the pairs the demand needs — the biochemical threshold effect (Rossignol et
al. 2003) — and a cell with no reserve has no threshold at all.

**Refusals rather than defaults**: a process outside Glycolysis, TCA and OXPHOS; a regenerated pool
without Glycolysis (glucose enters only there); TCA without OXPHOS (nothing would reoxidise its NADH);
OXPHOS with no compartment reading chrM, no `O2` pool or no stated capacity; no `Glucose` pool; a
stoichiometric constant the program does not state or states as unknown; more than one pool
regenerated by these processes.

What it does not do: kinetics. A steady-state concentration (of ATP, of 2,3-BPG) needs rate laws this
module does not carry, so it reports fluxes per hour and never a level.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from genomeos.ir import UNKNOWN, Compartment, Event, Module, Pool, to_minutes
from genomeos.runtime.economy import Economy

#: the processes of the reduced module, in the order glucose meets them
PROCESSES = ("Glycolysis", "TCA", "OXPHOS")

#: the stoichiometric constants the program must state (bio.std.core_metabolism states them all)
CONSTANTS = (
    "glycolysis_atp",
    "glycolysis_nadh",
    "glycolysis_pyruvate",
    "shunt_atp_lost",
    "lactate_per_pyruvate",
    "tca_nadh",
    "tca_fadh2",
    "tca_atp",
    "po_nadh",
    "po_fadh2",
    "po_nadh_low",
    "po_fadh2_low",
    "o2_per_pair",
)
PREFIX = "core_metabolism."

#: the two ends of the yields' spread: which P/O constants, and how cytosolic NADH reaches the chain
ARMS = ("high", "low")

#: the pools the reduced module reads its substrates from, and the cell's own facts
GLUCOSE, O2 = "Glucose", "O2"
CAPACITY_PARAM = "oxphos_capacity_per_copy"
SHUNT_PARAM = "bpg_shunt"


class MetabolismError(ValueError):
    """A program whose metabolism cannot be run as written."""


def per_hour(rate: float, unit: str) -> float:
    """An event's rate in its unit (`/h`, `1/yr`, ...), per hour."""
    per = unit[1:] if unit.startswith("/") else unit[2:] if unit.startswith("1/") else ""
    return rate * 60.0 / to_minutes(1.0, per)


@dataclass
class Flux:
    """One arm's steady state per hour: what was demanded, what was made, from what, and the cut."""

    arm: str
    demand: float
    supply: float
    max_supply: float
    oxidised: float  # glucose oxidised in full, per hour
    fermented: float  # glucose ending as lactate, per hour
    o2: float
    lactate: float
    shunt_flux: float  # 2,3-BPG made per hour
    atp_by_process: dict[str, float]
    yield_aerobic: float
    yield_anaerobic: float
    limit: str  # what bounded the oxidation: demand, oxygen, capacity, glucose, or none (no OXPHOS)
    factors: dict[str, float] = field(default_factory=dict)

    @property
    def glucose(self) -> float:
        return self.oxidised + self.fermented

    @property
    def met(self) -> float:
        return 1.0 if self.demand == 0 else self.supply / self.demand

    @property
    def oxphos_share(self) -> float:
        return 0.0 if self.supply == 0 else self.atp_by_process["OXPHOS"] / self.supply

    def readings(self) -> dict[str, float]:
        out = {
            "atp_supply": self.supply,
            "atp_demand": self.demand,
            "max_supply": self.max_supply,
            "met": self.met,
            "glucose_uptake": self.glucose,
            "glucose_oxidised": self.oxidised,
            "glucose_fermented": self.fermented,
            "o2_uptake": self.o2,
            "lactate": self.lactate,
            "bpg_shunt_flux": self.shunt_flux,
            "oxphos_share": self.oxphos_share,
            "yield_aerobic": self.yield_aerobic,
            "yield_anaerobic": self.yield_anaerobic,
        }
        out.update({f"atp.{p}": v for p, v in self.atp_by_process.items()})
        out.update({f"factor.{c}": v for c, v in self.factors.items()})
        return out


@dataclass
class Metabolism:
    """A program's energy currency, the processes that refill it and the facts that bound them."""

    module: Module
    pool: Pool
    processes: tuple[str, ...]
    constants: dict[str, float]
    glucose_uptake: float
    o2_supply: float
    copies: float
    mutant_copies: float
    capacity: float  # electron pairs per hour the unmutated copies can carry
    shunt: float
    work: dict[str, float]  # entity or event id -> units of work per hour

    @classmethod
    def from_module(
        cls,
        module: Module,
        supply: dict[str, float] | None = None,
        work: dict[str, float] | None = None,
    ) -> Metabolism:
        """Read the metabolism a program declares. `supply` overrides a pool's per-hour rate (an
        experiment: `{"O2": 0.0}` is anoxia); `work` adds units of work per hour for genes and proteins,
        which the program does not state as rates. An event's work is its own declared rate."""
        supply = dict(supply or {})
        pools = [e for e in module.entities.values() if isinstance(e, Pool)]
        stray = sorted(k for k in supply if not isinstance(module.entities.get(k), Pool))
        if stray:
            raise MetabolismError(f"a supply is set for {', '.join(stray)}, which no pool declares")
        regenerated = [p for p in pools if p.regenerates_from]
        if not regenerated:
            raise MetabolismError("no pool is regenerated `from` a process; there is no metabolism to run")
        if len(regenerated) > 1:
            names = ", ".join(sorted(p.id for p in regenerated))
            raise MetabolismError(
                f"pools {names} are all regenerated by processes; the module makes one currency"
            )
        pool = regenerated[0]
        processes = tuple(pool.regenerates_from)
        unknown = [p for p in processes if p not in PROCESSES]
        if unknown:
            raise MetabolismError(
                f"pool {pool.id} is regenerated from {', '.join(unknown)}; the reduced module (§6) runs "
                f"{', '.join(PROCESSES)} only"
            )
        if "Glycolysis" not in processes:
            raise MetabolismError(f"pool {pool.id} is not regenerated from Glycolysis, where glucose enters")
        if "TCA" in processes and "OXPHOS" not in processes:
            raise MetabolismError(
                f"pool {pool.id} names TCA without OXPHOS: nothing would reoxidise its NADH"
            )
        constants = _constants(module)
        glucose_uptake = _rate(module, GLUCOSE, supply, "glycolysis has no substrate")
        oxphos = "OXPHOS" in processes
        mito = [e for e in module.entities.values() if isinstance(e, Compartment) and e.mitochondrial]
        copies = float(sum(c.copies for c in mito))
        mutant = float(sum(c.copies * sum(c.heteroplasmy.values()) for c in mito))
        capacity = 0.0
        o2_supply = 0.0
        if oxphos:
            if not mito:
                raise MetabolismError(
                    f"pool {pool.id} is regenerated from OXPHOS and no compartment's genome reads chrM: "
                    "oxidative phosphorylation needs a mitochondrion"
                )
            o2_supply = _rate(module, O2, supply, "oxidative phosphorylation has no oxygen")
            per_copy = module.parameters.get(CAPACITY_PARAM)
            if per_copy is None or per_copy.value is UNKNOWN:
                raise MetabolismError(
                    f"OXPHOS runs and `param {CAPACITY_PARAM}` (electron pairs per hour per mitochondrial "
                    "copy) is not stated; the engine does not invent a capacity"
                )
            capacity = float(per_copy.value) * (copies - mutant)
        elif O2 in module.entities:
            o2_supply = _rate(module, O2, supply, "")
        shunt = 0.0
        if SHUNT_PARAM in module.parameters:
            value = module.parameters[SHUNT_PARAM].value
            if value is UNKNOWN or not 0.0 <= float(value) <= 1.0:
                raise MetabolismError(f"`param {SHUNT_PARAM}` is a fraction of glycolytic flux, within 0..1")
            shunt = float(value)
        rates = {
            ev.id: per_hour(ev.rate, ev.rate_unit)
            for ev in module.events
            if isinstance(ev, Event) and any(c.pool == pool.id for c in ev.costs)
        }
        rates.update(work or {})
        return cls(
            module=module,
            pool=pool,
            processes=processes,
            constants=constants,
            glucose_uptake=glucose_uptake,
            o2_supply=o2_supply,
            copies=copies,
            mutant_copies=mutant,
            capacity=capacity,
            shunt=shunt,
            work=rates,
        )

    # ---- the arithmetic --------------------------------------------------------------------
    def economy(self, capacity: float | None = None) -> Economy:
        """The program's economy, with this pool held against `capacity` (or its stock)."""
        cap = {} if capacity is None else {self.pool.id: capacity}
        return Economy.from_module(self.module, capacity=cap)

    def demand(self) -> float:
        """ATP per hour the program's work draws, through its declared costs (stage 2)."""
        return self.economy().demand_by_pool(self.work).get(self.pool.id, 0.0)

    def yields(self, arm: str) -> dict[str, float]:
        """Per glucose: ATP made glycolytically, by TCA and by OXPHOS when oxidised in full; the
        electron pairs and the O2 that takes."""
        k = self.constants
        if arm == "high":
            pn, pf, pc = k["po_nadh"], k["po_fadh2"], k["po_nadh"]  # malate-aspartate: cytosolic NADH as NADH
        elif arm == "low":
            pn, pf, pc = k["po_nadh_low"], k["po_fadh2_low"], k["po_fadh2_low"]  # glycerol 3-phosphate
        else:
            raise MetabolismError(f"arm {arm!r}: expected one of {', '.join(ARMS)}")
        pyr = k["glycolysis_pyruvate"]
        glycolytic = k["glycolysis_atp"] - pyr * self.shunt * k["shunt_atp_lost"]
        pairs = k["glycolysis_nadh"] + pyr * (k["tca_nadh"] + k["tca_fadh2"])
        return {
            "glycolytic": glycolytic,
            "tca": pyr * k["tca_atp"],
            "oxphos": pyr * (k["tca_nadh"] * pn + k["tca_fadh2"] * pf) + k["glycolysis_nadh"] * pc,
            "pairs": pairs,
            "o2": pairs * k["o2_per_pair"],
        }

    def solve(self, arm: str) -> Flux:
        """The steady state per hour in one arm: oxidise first, ferment the rest, cut what is short."""
        y = self.yields(arm)
        k = self.constants
        y_full = y["glycolytic"] + y["tca"] + y["oxphos"]
        glucose = self.glucose_uptake
        if "OXPHOS" in self.processes:
            bounds = {
                "oxygen": self.o2_supply / y["o2"],
                "capacity": self.capacity / y["pairs"],
                "glucose": glucose,
            }
            limit = min(bounds, key=lambda b: bounds[b])
            a_max = max(0.0, bounds[limit])
        else:
            limit, a_max = "none", 0.0
        max_supply = a_max * y_full + (glucose - a_max) * y["glycolytic"]
        demand = self.demand()
        if demand <= max_supply:
            supply = demand
            if a_max > 0 and demand / y_full <= a_max:
                oxidised, fermented, limit = demand / y_full, 0.0, "demand"
            else:
                oxidised = a_max
                rest = max(0.0, demand - oxidised * y_full)
                fermented = rest / y["glycolytic"] if y["glycolytic"] > 0 else 0.0
        else:
            oxidised, fermented, supply = a_max, glucose - a_max, max_supply
        by_process = {
            "Glycolysis": (oxidised + fermented) * y["glycolytic"],
            "TCA": oxidised * y["tca"],
            "OXPHOS": oxidised * y["oxphos"],
        }
        pyr = k["glycolysis_pyruvate"]
        flux = Flux(
            arm=arm,
            demand=demand,
            supply=supply,
            max_supply=max_supply,
            oxidised=oxidised,
            fermented=fermented,
            o2=oxidised * y["o2"],
            lactate=fermented * pyr * k["lactate_per_pyruvate"],
            shunt_flux=(oxidised + fermented) * pyr * self.shunt,
            atp_by_process=by_process,
            yield_aerobic=y_full,
            yield_anaerobic=y["glycolytic"],
            limit=limit,
        )
        flux.factors = self.economy(capacity=supply).scale(self.work)
        return flux

    def available(self, hours: float, arm: str) -> float:
        """ATP a draw can be paid from over `hours`: the pool's stock plus what the cell can make over
        that time beyond what its own work takes. This is what stage 4's resource checkpoint lacked."""
        flux = self.solve(arm)
        stock = float(self.pool.size) if self.pool.size is not UNKNOWN else 0.0
        return stock + max(0.0, flux.max_supply - flux.demand) * hours

    def readings(self) -> dict[str, float]:
        """Flat readings for `bio test`: `copies`, `capacity`, ..., and `<arm>.<reading>` per arm."""
        out: dict[str, float] = {
            "copies": self.copies,
            "mutant_copies": self.mutant_copies,
            "capacity": self.capacity,
            "glucose_supply": self.glucose_uptake,
            "o2_supply": self.o2_supply,
            "bpg_shunt": self.shunt,
        }
        for arm in ARMS:
            out.update({f"{arm}.{key}": v for key, v in self.solve(arm).readings().items()})
        return out

    def report(self) -> dict[str, Any]:
        arms = {}
        for arm in ARMS:
            flux = self.solve(arm)
            arms[arm] = {**flux.readings(), "limit": flux.limit}
        return {
            "pool": self.pool.id,
            "processes": list(self.processes),
            "copies": self.copies,
            "mutant_copies": self.mutant_copies,
            "capacity_pairs_per_h": self.capacity,
            "glucose_uptake_ceiling_per_h": self.glucose_uptake,
            "o2_supply_per_h": self.o2_supply,
            "bpg_shunt": self.shunt,
            "work_per_h": dict(sorted(self.work.items())),
            "arms": arms,
        }


def _constants(module: Module) -> dict[str, float]:
    missing, unknown, out = [], [], {}
    for name in CONSTANTS:
        p = module.parameters.get(PREFIX + name)
        if p is None:
            missing.append(PREFIX + name)
        elif p.value is UNKNOWN:
            unknown.append(PREFIX + name)
        else:
            out[name] = float(p.value)
    if missing or unknown:
        why = []
        if missing:
            why.append(f"not stated: {', '.join(missing)}")
        if unknown:
            why.append(f"stated as unknown: {', '.join(unknown)}")
        raise MetabolismError(
            "the engine holds no stoichiometry; import bio.std.core_metabolism or state it ("
            + "; ".join(why)
            + ")"
        )
    return out


def _rate(module: Module, pool_id: str, supply: dict[str, float], why: str) -> float:
    """A substrate pool's per-hour rate: the override if one is given, else its `regenerates` rate.
    The pool must be declared either way: an override sets a declared pool's supply, never makes one."""
    pool = module.entities.get(pool_id)
    if not isinstance(pool, Pool):
        raise MetabolismError(f"no pool {pool_id} is declared: {why}")
    if pool_id in supply:
        rate = float(supply[pool_id])
        if rate < 0:
            raise MetabolismError(f"a supply of {pool_id} cannot be negative")
        return rate
    if pool.regeneration is UNKNOWN:
        raise MetabolismError(f"pool {pool_id} states no `regenerates` rate per hour: {why or 'no supply'}")
    return float(pool.regeneration)
